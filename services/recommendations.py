def format_vk_text(text: str) -> str:
    """Format markdown and HTML text for clean rendering in VK messages."""
    # Convert markdown links [Label](URL) to Label (URL)
    text = re.sub(r"\[([^\]]+)\]\((https?://[^\)]+)\)", r"\1 (\2)", text)
    # Convert HTML links <a href="URL">Label</a> to Label (URL)
    text = re.sub(r'<a\s+href=[\"\']([^\"\']+)[\"\']>([^<]+)</a>', r"\2 (\1)", text)
    # Strip HTML tags
    text = re.sub(r"</?(?:b|i|code|strong|em|p|div|span|u|s)>", "", text)
    # Unescape HTML entities
    text = html.unescape(text)
    return text.strip()


